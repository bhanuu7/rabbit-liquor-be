app.post("/add", async (req, res) => {
  const { item_name, stock_count, price, category, image_url } = req.body;
  // Basic validation to ensure we don't send nulls to RDS
  if (!item_name || stock_count === undefined || !price || !category) {
    return res
      .status(400)
      .json({ error: "Please provide item_name, stock_count, and price" });
  }

  try {
    const query = `
      INSERT INTO inventory (item_name, stock_count, price, category, image_url) 
      VALUES ($1, $2, $3, $4, $5) 
      RETURNING *;
    `;
    const values = [item_name, stock_count, price, category, image_url];

    const result = await pool.query(query, values);

    // Return the newly created product (including the ID generated by RDS)
    res.status(201).json({
      message: "Product added successfully",
      product: result.rows[0],
    });
  } catch (err) {
    console.error("Database Error:", err.message);
    res.status(500).json({
      error: "Server error while adding product",
      message: err.message,
    });
  }
});

