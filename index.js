app.post("/reserve", async (req, res) => {
  const { customer_name, phone, email, items, total_price, user_name } =
    req.body;
  console.log("payload", req.body);
  if (!customer_name || !email || !items || items.length === 0) {
    return res.status(400).json({ error: "Invalid payload" });
  }
  const client = await pool.connect();
  console.log("client======>", client);
  try {
    await client.query("BEGIN");
    const productIds = items.map((i) => i.productId);
    console.log("productIds", productIds);
    // 🔒 Lock all required products
    const productsResult = await client.query(
      `SELECT * FROM inventory 
       WHERE id = ANY($1)
       FOR UPDATE NOWAIT`,
      [productIds],
    );

    console.log("productsResult", productsResult);
    const products = productsResult.rows;

    // Validate stock
    for (let item of items) {
      const product = products.find((p) => p.id === item.productId);

      if (!product) {
        throw new Error(`Product not found: ${item.productId}`);
      }

      if (product.stock_count < item.quantity) {
        throw new Error(`Out of stock for ${product.item_name}`);
      }
    }

    // 🧾 Insert order
    const orderResult = await client.query(
      `INSERT INTO orders (customer_name, email, phone, status, total_amount, user_name)
       VALUES ($1, $2, $3, 'order_placed', $4, $5)
       RETURNING id`,
      [customer_name, email, phone, total_price, user_name],
    );

    console.log("order result", orderResult);
    const orderId = orderResult.rows[0].id;

    // 📦 Insert order items + update inventory
    for (let item of items) {
      const product = products.find((p) => p.id === item.productId);

      // Insert order item
      await client.query(
        `INSERT INTO order_items 
         (order_id, product_id, quantity, price_at_purchase)
         VALUES ($1, $2, $3, $4)`,
        [orderId, item.productId, item.quantity, product.price],
      );

      // Update inventory
      const updated = await client.query(
        `UPDATE inventory
         SET stock_count = stock_count - $1,
             updated_at = CURRENT_TIMESTAMP
         WHERE id = $2
         RETURNING id, stock_count`,
        [item.quantity, item.productId],
      );

      console.log("updated items", updated);
      // 🔥 Emit per product update
      io.emit("inventory:update", {
        productId: updated.rows[0].id,
        stock_count: updated.rows[0].stock_count,
      });
    }

    await client.query("COMMIT");

    return res.json({
      success: true,
      orderId,
    });
  } catch (err) {
    console.error("Reserve Error:", err.message);
    await client.query("ROLLBACK");
    return res.status(500).json({
      success: false,
      message: "Internal server error",
    });
  } finally {
    client.release();
  }
});

